let orderCounter = 100;
for (const b of BUILDINGS) {
  const tiers = BUILDING_TIERS_DATA[b.id];
  tiers.forEach(([id, name, icon, price, reqOwned, desc, quote], idx) => {
    BUILDING_TIER_UPGRADES.push({
      id,
      name,
      icon,
      price,
      desc: `${b.plural} are **twice** as efficient. ${desc}`,
      quote,
      category: b.id === 'kentongan' ? 'kentongan' : 'building',
      pool: 'normal',
      order: orderCounter++,
      unlock: (state) => ownedCount(state, b.id) >= reqOwned,
      effect: b.id === 'kentongan'
        ? { type: 'kentongan_mult', mult: 2 }
        : { type: 'building_mult', buildingId: b.id, mult: 2 },
    });
  });
}

